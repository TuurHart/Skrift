def conversation(slug, turns, slot_names, **kw):
    def label(t):
        return slot_names.get(str(t["speaker"]), "Speaker %d" % (t["speaker"] + 1))
    body = "\n\n".join("**%s:** %s" % (label(t), t["text"]) for t in turns)
